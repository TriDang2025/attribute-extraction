CREATE TABLE "train" (
  "date" TEXT,
  "destination" TEXT,
  "number of people" INTEGER,
  "price" NUMERIC(10, 2),
  "time int" TIME,
  "train name" TEXT,
  "travel time" INTERVAL,
  PRIMARY KEY ("number of people")
);

CREATE TABLE "hotel" (
  "address" TEXT,
  "amenity part" TEXT,
  "amenity str" TEXT,
  "checkin date" TEXT,
  "day" TEXT,
  "day of week" TEXT,
  "entity name" TEXT,
  "hotel name" TEXT,
  "hotel rating" INTEGER,
  "location" TEXT,
  "location name" TEXT,
  "location part" TEXT,
  "lodging type" TEXT,
  "num" INTEGER,
  "num people" INTEGER,
  "phone number" INTEGER,
  "price range" TEXT,
  "rating" TEXT,
  "str" TEXT,
  "time" TIME,
  "type" TEXT,
  PRIMARY KEY ("address")
);

CREATE TABLE "restaurant" (
  "departure day" TEXT,
  "reference number" INTEGER,
  "time str" TIME,
  "confirmation number" INTEGER,
  "college name" TEXT,
  "cuisine" TEXT,
  "date" TEXT,
  "entrance fee" NUMERIC(10, 2),
  "location" TEXT,
  "location str" TEXT,
  "num options" INTEGER,
  "num people" INTEGER,
  "number of colleges" INTEGER,
  "party size" INTEGER,
  "phone number" INTEGER,
  "postcode" INTEGER,
  "price" TEXT,
  "price range" TEXT,
  "reference number (restaurant:15)" INTEGER,
  "restaurant info" TEXT,
  "restaurant name" TEXT,
  "str" TEXT,
  "table booking" TEXT,
  "table reservation time" TIME,
  "time" TIME,
  PRIMARY KEY ("reference number (restaurant:15)")
