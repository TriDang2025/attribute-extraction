  "train id" INTEGER,
  "description" TEXT,
  "duration" INTERVAL,
  "departure" TEXT,
  "destination" TEXT,
  "leave at" TIME,
  "price" NUMERIC(10, 2),
  "day" TEXT,
  "people" INTEGER,
  "reference" INTEGER,
  "Train duration" INTERVAL,
  "Train trainid" INTEGER,
  "Train departure" TEXT,
  "Train destination" TEXT,
  "Train leave at" TIME,
  "Train price" NUMERIC(10, 2),
  "Train day" TEXT,
  "Train requested people" INTEGER,
  "Train confirmed reference" INTEGER,
  "Train arrive by" TIME,
  PRIMARY KEY ("train id"),
  FOREIGN KEY ("departure") REFERENCES "train_info" ("departure"),
  FOREIGN KEY ("destination") REFERENCES "train_info" ("destination"),
  FOREIGN KEY ("leave at") REFERENCES "train_info" ("leave at"),
  FOREIGN KEY ("price") REFERENCES "train_info" ("price"),
  FOREIGN KEY ("day") REFERENCES "train_info" ("day"),
  FOREIGN KEY ("people") REFERENCES "train_info" ("people"),
  FOREIGN KEY ("reference") REFERENCES "train_info" ("reference")
);

