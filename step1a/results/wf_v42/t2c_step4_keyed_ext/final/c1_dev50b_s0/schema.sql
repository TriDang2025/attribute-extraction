CREATE TABLE "train_info" (
  "train id" INTEGER,
  "arrival time" TIME,
  "day" TEXT,
  "departure location" TEXT,
  "destination" TEXT,
  "duration" INTERVAL,
  "leaving time" TIME,
  "price" NUMERIC(10, 2),
  "people" INTEGER,
  "Train arrive by" TIME,
  "Train day" TEXT,
  "Train departure" TEXT,
  "Train destination" TEXT,
  "Train duration" INTERVAL,
  "Train leave at" TIME,
  "Train price" NUMERIC(10, 2),
  "Train requested people" INTEGER,
  "Train trainid" INTEGER,
  PRIMARY KEY ("train id")
);

CREATE TABLE "hotel_info" (
  "hotel id" INTEGER,
  "address" TEXT,
  "area" TEXT,
  "name" TEXT,
  "phone" INTEGER,
  "postcode" INTEGER,
  "price range" TEXT,
  "day" TEXT,
  "people" INTEGER,
  "stay" INTEGER,
  "stars" INTEGER,
  "type" TEXT,
  "Hotel address" TEXT,
  "Hotel area" TEXT,
  "Hotel name" TEXT,
  "Hotel phone" INTEGER,
  "Hotel postcode" INTEGER,
  "Hotel price range" TEXT,
  "Hotel requested day" TEXT,
  "Hotel requested people" INTEGER,
  "Hotel requested stay" INTEGER,
  "Hotel stars" INTEGER,
  "Hotel type" TEXT,
  PRIMARY KEY ("hotel id")
);

CREATE TABLE "restaurant_info" (
  "restaurant id" INTEGER,
  "address" TEXT,
  "area" TEXT,
  "name" TEXT,
  "phone" INTEGER,
  "postcode" TEXT,
  "price range" TEXT,
  "day" TEXT,
  "people" INTEGER,
  "time" TIME,
  "Restaurant address" TEXT,
  "Restaurant area" TEXT,
  "Restaurant food" TEXT,
  "Restaurant name" TEXT,
  "Restaurant phone" INTEGER,
  "Restaurant postcode" TEXT,
  "Restaurant price range" TEXT,
  "Restaurant requested day" TEXT,
  "Restaurant requested people" INTEGER,
  "Restaurant requested time" TIME,
  PRIMARY KEY ("restaurant id")
);

CREATE TABLE "booking_reference" (
  "reference id" INTEGER,
  "train reference" INTEGER,
  "hotel reference" INTEGER,
  "restaurant reference" INTEGER,
  "Train confirmed reference" INTEGER,
  "Hotel confirmed reference" INTEGER,
  "Restaurant confirmed reference" INTEGER,
  PRIMARY KEY ("reference id"),
  FOREIGN KEY ("train reference") REFERENCES "train_info" ("train id"),
  FOREIGN KEY ("hotel reference") REFERENCES "hotel_info" ("hotel id"),
  FOREIGN KEY ("restaurant reference") REFERENCES "restaurant_info" ("restaurant id")
);
